"""Writes the MindCollector Auction House addon's GearIds.lua: every weapon and armour item number in
WoW: Forever's client data, for the addon's item sweep (/mco items, 2026-11-26).

The client's Item table lists every item number (32,012 on 2026-11-26), but its ItemSparse, where the
stats are, holds only some of them (7,921 of the 19,048 weapons and armour): the server sends the rest
the first time the game shows an item. So the addon asks the game for each number here and keeps what
comes back. Numbers the server refuses are not in Forever: items from other WoW versions that share
the file, and raid gear before the raid opens.

    python gear_ids.py <Item.csv from wago.tools, product wowf> <path to GearIds.lua>

Item.csv: https://wago.tools/db2/Item/csv?product=wowf. Packed as one string of gaps between sorted
numbers, so 19,048 numbers take about 60 KB.
"""
import csv
import sys

SRC, OUT = sys.argv[1], sys.argv[2]
ids = []
with open(SRC, newline='', encoding='utf-8') as f:
    for r in csv.DictReader(f):
        # ClassID 2 weapon, 4 armour; InventoryType 0 is not worn (some armour-class oddments)
        if int(r['ClassID']) in (2, 4) and int(r['InventoryType']) > 0:
            ids.append(int(r['ID']))
ids.sort()
gaps, last = [], 0
for i in ids:
    gaps.append(i - last)
    last = i
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('-- Generated by tools/forever-market/gear_ids.py from the WoW: Forever client data (wago.tools\n')
    f.write('-- product wowf, Item ClassID 2 and 4). Do not edit by hand; re-run the script.\n')
    f.write('-- Every weapon and armour item number, as gaps between sorted numbers, for /mco items.\n')
    f.write('local _, ns = ...\n')
    f.write('ns.gearGaps = "' + ','.join(map(str, gaps)) + '"\n')
print(f'{len(ids)} item numbers, {ids[0]} to {ids[-1]}')
